    """
    Train RD++ on a prepared dataset split.

    Args:
        split_dir:            Path to split (must contain train/good/).
        output_dir:           Where to save model checkpoints.
        image_size:           Resize target (square).
        batch_size:           Batch size for training.
        epochs:               Maximum training epochs.
        proj_lr:              Learning rate for projection layer (Adam).
        distill_lr:           Learning rate for decoder + BN (Adam).
        weight_proj:          Weight for projection loss in total loss.
        accumulation_steps:   Gradient accumulation steps.
        patience:             Early stopping patience (epochs w/o improvement).
        min_train_images:     Minimum OK images required.

    Returns:
        Path to the best model checkpoint (.pth file).
    """
    split_dir = Path(split_dir)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    logger.info(f"Training RD++  |  split={split_dir}  device={device}")

    # ------------------------------------------------------------------
    # Guard: minimum training images
    # ------------------------------------------------------------------
    # Support both new (ok/) and legacy (good/) directory names
    train_dir = split_dir / "train" / "ok"
    if not train_dir.is_dir():
        train_dir = split_dir / "train" / "good"
    n_images = sum(
        1
        for p in train_dir.iterdir()
        if p.is_file() and p.suffix.lower() in IMAGE_EXTENSIONS
    )

    if n_images < min_train_images:
        msg = (
            f"\n{'=' * 60}\n"
            f"  TRAINING REJECTED: not enough OK images\n"
            f"  Found:    {n_images} images\n"
            f"  Required: at least {min_train_images}\n"
            f"\n"
            f"  RD++ needs ≥ {min_train_images} OK images for the\n"
            f"  decoder to learn meaningful feature reconstructions.\n"
            f"\n"
            f"  Please collect more OK samples and try again.\n"
            f"{'=' * 60}"
        )
        logger.error(msg)
        raise ValueError(msg)

    logger.info(f"Training images: {n_images}")

    # ------------------------------------------------------------------
    # Step 1: Data
    # ------------------------------------------------------------------
    train_dataset = TrainingDataset(
        train_dir,
        image_size=image_size,
        geometric_transform=benchmark_geometric_transform,
    )
    # In benchmark mode, use num_workers=0 to ensure np.random reproducibility
    # (TrainingDataset uses np.random for pseudo-anomaly generation).
    if benchmark_mode:
        n_workers = 0
        dl_generator = torch.Generator()
        dl_generator.manual_seed(42)  # seeded from set_seed() earlier
    else:
        n_workers = min(4, max(1, len(train_dataset)))
        dl_generator = None
    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=n_workers,
        pin_memory=(device.type == "cuda") and n_workers > 0,
        drop_last=(len(train_dataset) > batch_size),
        generator=dl_generator,
    )

    # ------------------------------------------------------------------
    # Step 2: Build models
    # ------------------------------------------------------------------
    encoder = Encoder().to(device)
    encoder.eval()

    bn = BottleneckNetwork().to(device)
    decoder = Decoder().to(device)
    proj_layer = MultiProjectionLayer(base=64).to(device)

    proj_loss_fn = Revisit_RDLoss()

    n_params = (
        sum(p.numel() for p in bn.parameters())
        + sum(p.numel() for p in decoder.parameters())
        + sum(p.numel() for p in proj_layer.parameters())
    )
    logger.info(f"Trainable parameters: {n_params:,}")

    # ------------------------------------------------------------------
    # Step 3: Optimisers (separate for projection and distillation)
    # ------------------------------------------------------------------
    optimizer_proj = torch.optim.Adam(
        proj_layer.parameters(),
        lr=proj_lr,
        betas=(0.5, 0.999),
    )
    optimizer_distill = torch.optim.Adam(
        list(decoder.parameters()) + list(bn.parameters()),
        lr=distill_lr,
        betas=(0.5, 0.999),
    )

    # ------------------------------------------------------------------
    # Step 4: Training loop
    # ------------------------------------------------------------------
    best_loss = float("inf")
    patience_counter = 0
    best_epoch = 0
    best_ckpt_path = output_dir / "model_best.pth"

    logger.info(
        f"Training: max {epochs} epochs, patience={patience}, "
        f"batch={batch_size}, accum={accumulation_steps}, "
        f"proj_lr={proj_lr}, distill_lr={distill_lr}, "
        f"weight_proj={weight_proj}"
    )
    if not HAS_GEOMLOSS:
        logger.warning(
            "geomloss not installed — using MMD fallback for SSOT loss. "
            "Install geomloss for optimal results."
        )

    for epoch in range(1, epochs + 1):
        bn.train()
        decoder.train()
        proj_layer.train()

        epoch_loss_total = 0.0
        epoch_loss_distill = 0.0
        epoch_loss_proj = 0.0
        n_batches = 0

        optimizer_proj.zero_grad()
        optimizer_distill.zero_grad()

        for i, (img, img_noise) in enumerate(train_loader):
            img = img.to(device)
            img_noise = img_noise.to(device)

            # Frozen encoder — no gradients
            with torch.no_grad():
                inputs = encoder(img)
                inputs_noise = encoder(img_noise)

            # Projection (both normal and noisy)
            projected_noise, projected_normal = proj_layer(
                inputs,
                features_noise=inputs_noise,
            )

            # Projection loss (SSOT + reconstruct + contrast)
            L_proj = proj_loss_fn(inputs_noise, projected_noise, projected_normal)

            # Distillation loss (decoder reconstructs encoder features)
            outputs = decoder(bn(projected_normal))
            L_distill = distillation_loss(inputs, outputs)

            loss = L_distill + weight_proj * L_proj
            loss = loss / accumulation_steps
            loss.backward()

            if (i + 1) % accumulation_steps == 0:
                optimizer_proj.step()
                optimizer_distill.step()
                optimizer_proj.zero_grad()
                optimizer_distill.zero_grad()

            epoch_loss_total += L_distill.item() + weight_proj * L_proj.item()
            epoch_loss_distill += L_distill.item()
            epoch_loss_proj += L_proj.item()
            n_batches += 1

        # Flush remaining gradients
        if n_batches % accumulation_steps != 0:
            optimizer_proj.step()
            optimizer_distill.step()
            optimizer_proj.zero_grad()
            optimizer_distill.zero_grad()

        avg_total = epoch_loss_total / max(n_batches, 1)
        avg_distill = epoch_loss_distill / max(n_batches, 1)
        avg_proj = epoch_loss_proj / max(n_batches, 1)

        # ---- Early stopping ----
        min_delta = 1e-4
        if avg_total < best_loss - min_delta:
            best_loss = avg_total
            best_epoch = epoch
            patience_counter = 0
            _save_checkpoint(
                best_ckpt_path,
                decoder,
                bn,
                proj_layer,
                image_size,
            )
        else:
            patience_counter += 1

        # ---- Logging ----
        if epoch % 10 == 0 or epoch == 1 or epoch == epochs:
            logger.info(
                f"  Epoch {epoch:>3}/{epochs}  "
                f"L_total={avg_total:.4f}  L_dist={avg_distill:.4f}  "
                f"L_proj={avg_proj:.4f}  best={best_loss:.4f}  "
                f"patience={patience_counter}/{patience}"
            )

        if patience_counter >= patience:
            logger.info(
                f"  Early stopping at epoch {epoch} "
                f"(best epoch: {best_epoch}, best loss: {best_loss:.4f})"
            )
            break

    logger.info(
        f"Best checkpoint: {best_ckpt_path}  "
        f"(epoch {best_epoch}, loss={best_loss:.4f})"
    )
    return str(best_ckpt_path)


