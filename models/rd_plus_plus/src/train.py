def _save_checkpoint(
    path: Path,
    decoder: Decoder,
    bn: BottleneckNetwork,
    proj_layer: MultiProjectionLayer,
    image_size: int,
) -> None:
    config = {
        "image_size": image_size,
        "backbone": "wide_resnet50_2",
        "decoder_layers": (3, 4, 6),
        "width_per_group": 128,
        "proj_base": 64,
    }
    torch.save(
        {
            "decoder_state_dict": decoder.state_dict(),
            "bn_state_dict": bn.state_dict(),
            "proj_state_dict": proj_layer.state_dict(),
            "config": config,
        },
        path,
    )


