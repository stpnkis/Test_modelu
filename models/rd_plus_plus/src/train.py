class ImageFolderSimple(Dataset):
    """Load images from a flat directory (no labels)."""

    def __init__(
        self, root: str | Path, transform: transforms.Compose | None = None
    ) -> None:
        self.paths: list[Path] = sorted(
            p
            for p in Path(root).iterdir()
            if p.is_file() and p.suffix.lower() in IMAGE_EXTENSIONS
        )
        self.transform = transform

    def __len__(self) -> int:
        return len(self.paths)

    def __getitem__(self, idx: int) -> torch.Tensor:
        img = Image.open(self.paths[idx]).convert("RGB")
        if self.transform is not None:
            img = self.transform(img)
        return img


class TrainingDataset(Dataset):
    """Training dataset returning (normal_image, noisy_image) pairs.

    Generates pseudo-anomalies by injecting structured noise
    (multi-octave Gaussian-filtered random noise approximating simplex noise)
    into a random rectangular patch of each training image.

    Noise generation strategy:
      1. Pick a random rectangular region (10–size//8 pixels per side).
      2. Generate 6-octave spatially-correlated noise via Gaussian filtering.
      3. Add to the image at 20 % amplitude.
      This closely approximates the original RD++ simplex noise approach
      without requiring the numba dependency.
    """

    def __init__(
        self,
        root: str | Path,
        image_size: int = 256,
        geometric_transform=None,
    ) -> None:
        self.paths: list[Path] = sorted(
            p
            for p in Path(root).iterdir()
            if p.is_file() and p.suffix.lower() in IMAGE_EXTENSIONS
        )
        self.image_size = image_size
        self.geometric_transform = geometric_transform
        self.normalize = transforms.Normalize(mean=IMAGENET_MEAN, std=IMAGENET_STD)

    def __len__(self) -> int:
        return len(self.paths)

    def _generate_noise_patch(self, size: int) -> np.ndarray:
        """Multi-octave Gaussian noise patch (approximates simplex noise)."""
        h_noise = np.random.randint(10, max(11, size // 8))
        w_noise = np.random.randint(10, max(11, size // 8))
        start_h = np.random.randint(1, max(2, size - h_noise))
        start_w = np.random.randint(1, max(2, size - w_noise))

        noise = np.zeros((3, h_noise, w_noise), dtype=np.float32)
        amplitude = 1.0
        for octave in range(6):
            raw = np.random.randn(3, h_noise, w_noise).astype(np.float32)
            sigma = max(0.5, min(h_noise, w_noise) / (4 * (2**octave)))
            for c in range(3):
                raw[c] = scipy_gaussian_filter(raw[c], sigma=sigma)
            noise += amplitude * raw
            amplitude *= 0.6

        nmax = np.abs(noise).max() + 1e-8
        noise = noise / nmax

        mask = np.zeros((3, size, size), dtype=np.float32)
        mask[:, start_h : start_h + h_noise, start_w : start_w + w_noise] = 0.2 * noise
        return mask

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, torch.Tensor]:
        img = Image.open(self.paths[idx]).convert("RGB")

        if self.geometric_transform is not None:
            # Benchmark mode: apply shared geometric transforms, then to array
            img = self.geometric_transform(img)

        img = (
            img.resize((self.image_size, self.image_size), Image.BILINEAR)
            if self.geometric_transform is None
            else img
        )
        img_np = np.array(img, dtype=np.float32) / 255.0
        img_np = img_np.transpose(2, 0, 1)  # [3, H, W]

        # Normal image
        img_normal = self.normalize(torch.from_numpy(img_np.copy()))

        # Noisy image (pseudo-anomaly)
        noise_mask = self._generate_noise_patch(self.image_size)
        img_noisy = np.clip(img_np + noise_mask, 0.0, 1.0)
        img_noise = self.normalize(torch.from_numpy(img_noisy))

        return img_normal, img_noise


# ======================================================================== #
#  Anomaly map computation (used for validation during training)            #
# ======================================================================== #


def compute_anomaly_map(
    encoder_features: list[torch.Tensor],
    decoder_features: list[torch.Tensor],
    out_size: int,
) -> torch.Tensor:
    """Compute image-level anomaly map from encoder–decoder cosine distance.

    For each scale, 1 − cos_similarity is upsampled to out_size and summed.
    Returns: [B, out_size, out_size] anomaly map (higher = more anomalous).
    """
    B = encoder_features[0].shape[0]
    device = encoder_features[0].device
    anomaly_map = torch.zeros(B, out_size, out_size, device=device)

    for enc, dec in zip(encoder_features, decoder_features):
        a_map = 1 - F.cosine_similarity(enc, dec, dim=1)  # [B, H, W]
        a_map = F.interpolate(
            a_map.unsqueeze(1),
            size=out_size,
            mode="bilinear",
            align_corners=True,
        )
        anomaly_map += a_map.squeeze(1)

    return anomaly_map


