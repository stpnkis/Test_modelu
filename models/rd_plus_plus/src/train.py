"""
RD++ (Revisiting Reverse Distillation) Training Script
========================================================

Trains an RD++ anomaly-detection model (CVPR 2023, Tran Dinh Tien et al.)
on a folder of OK images with zero user interaction.

How RD++ works:
  1. A pretrained WideResNet-50-2 encoder extracts multi-scale features
     from layer1, layer2, layer3 (frozen — never updated).
  2. A Bottleneck Network (OCE-BN) aggregates and compresses the multi-scale
     features into a compact one-class embedding.
  3. A reverse decoder (mirror of the encoder with transposed convolutions)
     reconstructs the encoder features from the BN output.
  4. A Multi-Projection Layer projects encoder features for self-supervised
     optimal-transport (SSOT) regularisation.
  5. Pseudo-anomalies are generated by injecting structured noise
     (approximating simplex noise) into training images.

The core idea: the decoder learns to reconstruct normal features. At inference,
anomalous regions produce features the decoder cannot reconstruct, yielding
high cosine-distance anomaly scores.

Architecture (WideResNet-50-2 backbone):
  - Encoder:     frozen WRN50-2, returns [layer1(256ch), layer2(512ch), layer3(1024ch)]
  - BN layer:    aggregates 3 scales → [2048, 8, 8] bottleneck
  - Decoder:     reverse WRN50-2 with ConvTranspose2d → [256ch, 512ch, 1024ch]
  - Projection:  3× ProjLayer (conv bottleneck per scale)

Training losses:
  - L_distill:  cosine similarity between encoder and decoder features
  - L_proj:     (SSOT + 0.01×reconstruct + 0.1×contrastive) / 1.11
  - L_total:    L_distill + weight_proj × L_proj

Optimiser setup:
  - Projection:  Adam lr=1e-3, betas=(0.5, 0.999)
  - Distillation (decoder + BN): Adam lr=5e-3, betas=(0.5, 0.999)
  - Gradient accumulation: 2 steps (effective batch = 2 × batch_size)

Checkpoint format (.pth):
  { decoder_state_dict, bn_state_dict, proj_state_dict, config }
"""

